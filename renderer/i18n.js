let locale = 'zh-TW';

function t(key, vars) {
  const dict = DICT[locale] || DICT['zh-TW'];
  const entry = dict[key] != null ? dict[key] : (DICT['zh-TW'][key] != null ? DICT['zh-TW'][key] : key);
  return typeof entry === 'function' ? entry(vars || {}) : String(entry);
}

(function expose() {
  window.I18N = {
    setLocale(loc) {
      locale = loc === 'en' ? 'en' : 'zh-TW';
    },
    getLocale() {
      return locale;
    },
    t,
  };
})();
